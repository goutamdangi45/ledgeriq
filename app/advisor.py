"""Rule-based Smart Financial Advisor (REQ-F23 to REQ-F27). Pure functions: easy to unit test."""
from .utils import fmt_money

DISCLAIMER = ("These suggestions are general guidance generated by simple rules from the data you entered. "
              "They are not guaranteed outcomes and not a replacement for a professional financial advisor.")
MIN_TXNS = 8


def _s(sid, severity, title, message, why, action=None):
    return {"id": sid, "severity": severity, "title": title, "message": message, "why": why,
            "action": action, "source": "system-calculated"}


def generate(*, txn_count, months, cat_spend, budgets, goals, current_month, elapsed_fraction,
             currency="INR"):
    """
    months:     {YYYY-MM: {income, expense}}   (up to last 3 months incl. current)
    cat_spend:  {(YYYY-MM, category): minor}
    budgets:    [{month, category (None = total), planned}]
    goals:      [{name, remaining, monthly_needed, status}]
    """
    f = lambda v: fmt_money(v, currency)  # noqa: E731
    if txn_count < MIN_TXNS or not months:
        return {"enough_data": False, "suggestions": [_s(
            "need-data", "info", "Not enough data yet",
            f"Add at least {MIN_TXNS} transactions (about {max(MIN_TXNS - txn_count, 1)} more) so the advisor "
            "can spot useful patterns.",
            f"The advisor needs a minimum amount of history; you currently have {txn_count} recent transactions.",
            {"label": "Add a transaction", "route": "#/transactions"})], "disclaimer": DISCLAIMER}

    out = []
    done_months = [m for m in sorted(months) if m != current_month]
    cur = months.get(current_month, {"income": 0, "expense": 0})

    # R1/R2 - categories repeatedly above budget (REQ-F23)
    cat_budgets = [b for b in budgets if b["category"]]
    for cat in sorted({b["category"] for b in cat_budgets}):
        over = [b["month"] for b in cat_budgets if b["category"] == cat
                and cat_spend.get((b["month"], cat), 0) > b["planned"]]
        if len(over) >= 2:
            out.append(_s(f"over-{cat}", "high", f"{cat} is consistently above budget",
                          f"You spent more than your {cat} budget in {len(over)} of the last few months.",
                          f"Months over budget: {', '.join(sorted(over))}.",
                          {"label": "Review budgets", "route": "#/budgets"}))
        elif current_month in over:
            b = next(x for x in cat_budgets if x["category"] == cat and x["month"] == current_month)
            out.append(_s(f"over-now-{cat}", "medium", f"{cat} is over budget this month",
                          f"{cat} spending is {f(cat_spend[(current_month, cat)])} against a budget of "
                          f"{f(b['planned'])}. Consider reviewing recent {cat} purchases.",
                          "Current month spending is above the planned amount.",
                          {"label": "Review transactions", "route": "#/transactions"}))

    # pace warning on total budget
    tb = next((b for b in budgets if b["category"] is None and b["month"] == current_month), None)
    if tb and tb["planned"] and cur["expense"] <= tb["planned"] and elapsed_fraction > 0.05:
        pace = cur["expense"] / tb["planned"]
        if pace > elapsed_fraction + 0.2:
            out.append(_s("pace", "medium", "Spending is running ahead of your monthly budget",
                          f"You have used {pace * 100:.0f}% of your budget with {elapsed_fraction * 100:.0f}% "
                          "of the month gone.", "Compared budget used against the share of the month elapsed.",
                          {"label": "Adjust budget", "route": "#/budgets"}))

    # R3/R4 - cash flow and savings rate
    if cur["expense"] > cur["income"] and cur["expense"] > 0:
        out.append(_s("deficit", "high", "Expenses exceed income this month",
                      f"You have spent {f(cur['expense'])} against income of {f(cur['income'])}.",
                      "Current month expenses are greater than current month income.",
                      {"label": "See where money goes", "route": "#/reports"}))
    base = done_months or [current_month]
    inc = sum(months[m]["income"] for m in base)
    exp = sum(months[m]["expense"] for m in base)
    if inc > 0:
        rate = (inc - exp) / inc
        if rate < 0.10:
            out.append(_s("low-savings", "medium", "Your savings rate is low",
                          f"You kept about {max(rate, 0) * 100:.0f}% of your income. A common rule of thumb is "
                          "to aim for 20% where practical.", "Savings rate = (income - expenses) / income over recent months.",
                          {"label": "Set a savings goal", "route": "#/goals"}))
        elif rate >= 0.20:
            out.append(_s("good-savings", "positive", "Nice savings habit",
                          f"You kept about {rate * 100:.0f}% of your income recently. Keep it up!",
                          "Savings rate is at or above 20%.", {"label": "Put it toward a goal", "route": "#/goals"}))

    # R5 - dominant category
    totals = {}
    for (m, c), v in cat_spend.items():
        totals[c] = totals.get(c, 0) + v
    grand = sum(totals.values())
    if grand:
        top, val = max(totals.items(), key=lambda kv: kv[1])
        if val / grand > 0.40:
            out.append(_s("dominant", "low", f"{top} takes the largest share of spending",
                          f"{top} makes up {val * 100 / grand:.0f}% of your recent expenses ({f(val)}).",
                          "One category is more than 40% of total expenses.",
                          {"label": "Set a category budget", "route": "#/budgets"}))

    # R6 - big month-over-month jump
    if len(done_months) >= 2:
        last, prev = done_months[-1], done_months[-2]
        for c in sorted({c for (m, c) in cat_spend if m == last}):
            a, b = cat_spend.get((last, c), 0), cat_spend.get((prev, c), 0)
            if b > 0 and a >= b * 1.3 and a - b >= 50000:
                out.append(_s(f"jump-{c}", "low", f"{c} spending jumped",
                              f"{c} rose from {f(b)} in {prev} to {f(a)} in {last} "
                              f"(+{(a - b) * 100 / b:.0f}%).", "Month-over-month increase above 30%.",
                              {"label": "Review transactions", "route": "#/transactions"}))

    # R7 - no budgets
    if not [b for b in budgets if b["month"] == current_month]:
        out.append(_s("no-budget", "low", "You have no budget for this month",
                      "Setting even a total monthly limit makes alerts and advice more useful.",
                      "No budget was found for the current month.", {"label": "Create a budget", "route": "#/budgets"}))

    # R8 - goals vs surplus
    surplus = (inc - exp) // max(len(base), 1)
    for g in goals:
        if g["status"] != "active" or not g["monthly_needed"]:
            continue
        if g["monthly_needed"] > max(surplus, 0):
            out.append(_s(f"goal-{g['name']}", "medium", f"Goal “{g['name']}” may be out of reach",
                          f"It needs about {f(g['monthly_needed'])} per month, but your recent average "
                          f"surplus is about {f(max(surplus, 0))}. Consider a later date or a smaller target.",
                          "Required monthly saving compared with your recent average surplus.",
                          {"label": "Edit goal", "route": "#/goals"}))
        else:
            out.append(_s(f"goal-ok-{g['name']}", "positive", f"Goal “{g['name']}” looks achievable",
                          f"Saving about {f(g['monthly_needed'])} per month fits within your recent surplus.",
                          "Required monthly saving is below your recent average surplus.",
                          {"label": "View goals", "route": "#/goals"}))

    if not out:
        out.append(_s("all-good", "positive", "Nothing needs attention",
                      "Your recent spending looks steady. Keep tracking to unlock more insights.",
                      "No advisor rule was triggered.", None))
    order = {"high": 0, "medium": 1, "low": 2, "positive": 3, "info": 4}
    out.sort(key=lambda s: order[s["severity"]])
    return {"enough_data": True, "suggestions": out, "disclaimer": DISCLAIMER}
